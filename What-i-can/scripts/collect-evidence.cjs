// scripts/collect-evidence.cjs
// Take latest test results + fill in the evidence template.
// Run AFTER scripts/run-tests.cjs.
//
// Usage:
//   node scripts/run-tests.cjs   # generates test-results/latest.json
//   node scripts/collect-evidence.cjs   # fills evidence
//   # open evidence/A5-Team14-Integration-Evidence-FILLED.md
//   # copy content into the actual submission file (or rename)

const fs = require('fs');
const path = require('path');

const RESULTS = path.join(__dirname, '..', 'test-results', 'latest.json');
const TEMPLATE = path.join(__dirname, '..', 'evidence', 'A5-Team14-Integration-Evidence.md');
const OUTPUT = path.join(__dirname, '..', 'evidence', 'A5-Team14-Integration-Evidence-FILLED.md');

function main() {
  if (!fs.existsSync(RESULTS)) {
    console.error(`❌ Missing: ${RESULTS}`);
    console.error(`   Run first: node scripts/run-tests.cjs`);
    process.exit(1);
  }

  const results = JSON.parse(fs.readFileSync(RESULTS, 'utf8'));
  let template = fs.readFileSync(TEMPLATE, 'utf8');

  const find = (substr) => results.find(r => r.name.includes(substr));

  const consumer = find('Consumer Proof');
  const provider = find('Provider Proof');
  const recvBad = find('3a');
  const recvGood = find('3b');
  const sender = find('Sender');
  const idemFirst = find('Idempotency — first');
  const idemReplay = find('Idempotency — same call again');
  const degBreak = find('6a');
  const degFail = find('6b');
  const degHeal = find('6c');
  const degRecover = find('6d');

  // Fill replacements
  const replacements = {
    '_paste actual time from Postman runner_': consumer?.ts || 'N/A',
    '_paste actual response from Postman_': consumer ? JSON.stringify(consumer.response_body, null, 2) : 'N/A',

    '_paste actual wrangler tail output showing incoming webhook_': provider
      ? `Incoming POST to /webhooks/wellbeing at ${provider.ts}\nResponse: ${JSON.stringify(provider.response_body)}`
      : 'N/A',
    '_paste actual response_': provider ? JSON.stringify(provider.response_body, null, 2) : 'N/A',

    '_paste payload from test 3b_': recvGood ? JSON.stringify(recvGood.response_body, null, 2) : 'N/A',
    '_paste_': 'see Appendix D below',
    '| _paste_ | _paste_ | _paste_ | _paste_ |': recvGood
      ? `| evt-test-002 | wellbeing.case.opened | wellbeing | ${recvGood.ts} |`
      : '| (test 3b not run) | | | |',

    '_paste actual response — should include `X-Idempotent-Replay: true`_': idemReplay
      ? `${idemReplay.status} (X-Idempotent-Replay: ${idemReplay.response_headers['x-idempotent-replay'] || 'absent'})`
      : 'N/A',

    '_paste timestamp_': degBreak?.ts || 'N/A',

    '_paste wrangler tail output showing fallback + retry + recovery_': degBreak && degRecover
      ? `[${degBreak.ts}] partner degraded (POST /v1/_debug/break)\n[${degHeal?.ts || '?'}] partner healed (POST /v1/_debug/heal)\n[${degRecover.ts}] recovery call succeeded (${degRecover.status})`
      : 'N/A',

    '| _paste_ | _paste_ | _paste_ | _paste_ |': '| (no data) | | | |',
    '| idempotency_key | status | attempts | sent_at |': sender
      ? `| ${sender.request_headers['X-Idempotency-Key'] || ''} | sent | 1 | ${sender.ts} |`
      : '| (test 4 not run) | | |',
  };

  // Apply replacements (sequential, may overlap — first match wins)
  for (const [from, to] of Object.entries(replacements)) {
    if (template.includes(from)) {
      template = template.replace(from, to);
    }
  }

  // Append appendix with all raw outputs
  let appendix = `\n\n---\n\n# Appendix D — Raw Test Outputs (auto-generated)\n\n`;
  appendix += `Generated by \`scripts/collect-evidence.cjs\` on ${new Date().toISOString()}\n\n`;
  appendix += `Source: \`scripts/run-tests.cjs\` output → \`test-results/latest.json\`\n\n`;

  results.forEach((r) => {
    appendix += `## ${r.sequence}. ${r.name}\n\n`;
    appendix += `| Field | Value |\n|---|---|\n`;
    appendix += `| Status | ${r.passed ? '✅' : '❌'} ${r.status || 'ERR'} ${r.statusText || ''} |\n`;
    appendix += `| Method | ${r.method} |\n`;
    appendix += `| URL | \`${r.url}\` |\n`;
    appendix += `| Duration | ${r.duration_ms}ms |\n`;
    appendix += `| Timestamp | ${r.ts} |\n\n`;

    if (r.request_body) {
      appendix += `**Request body:**\n\`\`\`json\n${r.request_body}\n\`\`\`\n\n`;
    }

    if (r.response_body !== undefined) {
      appendix += `**Response body:**\n\`\`\`json\n${JSON.stringify(r.response_body, null, 2)}\n\`\`\`\n\n`;
    }

    if (r.response_headers && Object.keys(r.response_headers).length) {
      appendix += `**Response headers (relevant):**\n`;
      for (const [k, v] of Object.entries(r.response_headers)) {
        if (k.startsWith('x-') || k === 'content-type') {
          appendix += `- \`${k}: ${v}\`\n`;
        }
      }
      appendix += '\n';
    }

    if (r.error) {
      appendix += `**Error:** ${r.error}\n\n`;
    }

    appendix += '---\n\n';
  });

  // Build summary stats
  const passed = results.filter(r => r.passed).length;
  const failed = results.length - passed;

  let summary = `\n\n## Appendix E — Test Run Summary\n\n`;
  summary += `| Metric | Value |\n|---|---|\n`;
  summary += `| Total tests | ${results.length} |\n`;
  summary += `| Passed | ${passed} |\n`;
  summary += `| Failed | ${failed} |\n`;
  summary += `| Pass rate | ${((passed / results.length) * 100).toFixed(1)}% |\n`;
  summary += `| Run time | ${new Date(results[0]?.ts || Date.now()).toISOString()} |\n`;
  summary += `| Latest result | ${results[results.length - 1]?.name || 'N/A'} |\n`;

  template = template + appendix + summary;

  fs.writeFileSync(OUTPUT, template);

  console.log(`\n✅ Wrote filled evidence: ${OUTPUT}`);
  console.log(`   Tests: ${results.length} (${passed} passed, ${failed} failed)`);
  console.log(`   Next: open the file, review, copy sections into your submission doc`);
}

main().catch(e => { console.error('Fatal:', e); process.exit(1); });
